import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const P = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await ctx.newPage();
await page.goto(P + '/ariza-namunasi', { waitUntil: 'networkidle' });
await page.waitForSelector('#aiAriza', { state: 'visible' });
console.log('OK   UZ: AI bloki ko\'rinadi');
await page.screenshot({ path: path.join(dir, 'out', 'live-desktop.png') });
// haqiqiy so'rov
await page.fill('#aizIn', "bolam 3 kun kasal bo'ldi, maktabga yozishim kerak");
await page.click('#aizGo');
await page.waitForFunction(() => document.getElementById('aizGo').textContent === 'Matnni yozish' && document.getElementById('dgf-erkinMatn'), null, { timeout: 30000 });
const txt = await page.inputValue('#dgf-erkinMatn');
assert.ok(txt.split(/\s+/).length >= 25);
assert.ok((await page.textContent('#docBody')).includes(txt.split('\n')[0].slice(0, 25)));
console.log('OK   haqiqiy so\'rov: natija maydon va ko\'rik hujjatiga tushdi (' + txt.split(/\s+/).length + ' so\'z)');
await page.click('#aizCopy');
await page.waitForFunction(() => document.getElementById('aizCopy').textContent === 'Nusxalandi');
assert.equal(await page.evaluate(() => navigator.clipboard.readText()), txt);
console.log('OK   "Nusxa olish" yangi matnni nusxaladi');
await page.screenshot({ path: path.join(dir, 'out', 'live-natija.png') });
console.log('--- BRAUZER MATNI ---\n' + txt + '\n---');
await page.setViewportSize({ width: 320, height: 700 });
await page.reload({ waitUntil: 'networkidle' });
const m = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, iw: innerWidth }));
assert.ok(m.sw <= m.iw); console.log('OK   320px toshmaydi ' + JSON.stringify(m));
await page.evaluate(() => document.getElementById('aiAriza').scrollIntoView());
await page.screenshot({ path: path.join(dir, 'out', 'live-320.png') });
await page.goto(P + '/ru/ariza-namunasi', { waitUntil: 'networkidle' });
assert.equal(await page.evaluate(() => { const e = document.getElementById('aiAriza'); return !e || e.hidden || e.offsetParent === null; }), true);
console.log('OK   RU: blok ko\'rinmaydi');
await b.close();
